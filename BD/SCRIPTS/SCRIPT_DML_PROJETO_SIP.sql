-- EXEMPLOS DE UPDATE ()

SELECT * FROM T_SIP_PROJETO;


-- ALTERAR A DATA DE SAIDA DE UM DETERMINADO PROJETO
UPDATE T_SIP_PROJETO
    SET DT_TERMINO = TO_DATE('25/09/2026', 'DD/MM/YYYY')
WHERE CD_PROJETO = '1001';
-- CLAUSULA SET, É ONDE INDICAMOS O QUE SE DESEJA ALTERAR (COLUNAS)
-- A CONDIÇÃO (WHERE) VAI INDICAR QUAIS LINHAS SERÃO AFETADAS PELA ALTERAÇÃO
-- ATENÇÃO! SEMPRE QUE POSSÍVEL USAR A CHAVE PRIMÁRIA
-- (INDICE) PARA REALIZAR O FILTRO - ATUALIZAÇÃO MAIS EFICIENTE,
-- DEVIDO ENCONTRAR A LINHA DIRETAMENTE (MENOS ACESSO A DISCO) OU OUTRO CAMPO QUE SEJA INDICE
-- CUIDADO! UPDATE SEM WHERE, ALTERA TODAS AS LINHAS DE UMA TABELA

-- SIMULANDO UM UPDATE SEM WHERE
-- ALTERANDO MAIS DE UMA COLUNA
UPDATE T_SIP_PROJETO
SET DT_INICIO = TO_DATE('01/01/2026', 'DD/MM/YYYY'),
DT_TERMINO = TO_DATE('05/11/2026', 'DD/MM/YYYY');

-- DESFAZ UMA TRANSAÇÃO QUE AINDA NÃO SOFREU COMMIT
ROLLBACK;

